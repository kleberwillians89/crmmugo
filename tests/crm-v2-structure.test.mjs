assert.ok(migration.includes('enable row level security'))
assert.ok(migration.includes('public.current_organization_id()'))
assert.ok(migration.includes('public.can_write()'))
assert.ok(migration.includes('on conflict(organization_id,expense_id,reference_month,installment_number) do nothing'))
assert.match(migration,/foreign key\(organization_id,category_id\)/)
assert.match(migration,/foreign key\(organization_id,expense_id\)/)
assert.match(migration,/create trigger enforce_business_amount/)
assert.match(migration,/create trigger sync_installment_business_amounts/)
assert.match(migration,/revoke all on function public\.generate_expense_installments\(uuid\) from public/)
assert.doesNotMatch(migration,/for all to authenticated/)
assert.match(migration,/for insert to authenticated/)
assert.match(migration,/for update to authenticated/)
assert.match(migration,/expenses_org_deleted_idx/)
assert.match(migration,/expense_installments_expense_idx/)
assert.match(foundation,/current_organization_id\(\)/)
assert.match(foundation,/current_user_role\(\) in\('admin','manager'\)/)
