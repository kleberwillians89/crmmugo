assert.doesNotMatch(importMigration,/\b(insert|update|delete)\s+(into|public\.|from)/i)
assert.ok(!/\binsert into public\.(expenses|expense_installments)\b/i.test(migration.replace(/insert into public\.expense_installments\([\s\S]*?on conflict\([\s\S]*?;/i,'')),'Migration não deve semear despesas reais')
console.log('CRM V2 routes, RLS and idempotency: ok')
